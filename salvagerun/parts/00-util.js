function qaxis(ax, ang) { const s = Math.sin(ang / 2), n = vnorm(ax); return [n[0] * s, n[1] * s, n[2] * s, Math.cos(ang / 2)]; }
function qmul(a, b) {
  return [a[3] * b[0] + a[0] * b[3] + a[1] * b[2] - a[2] * b[1], a[3] * b[1] - a[0] * b[2] + a[1] * b[3] + a[2] * b[0],
    a[3] * b[2] + a[0] * b[1] - a[1] * b[0] + a[2] * b[3], a[3] * b[3] - a[0] * b[0] - a[1] * b[1] - a[2] * b[2]];
}
function qnorm(q) { const l = Math.hypot(q[0], q[1], q[2], q[3]) || 1; return [q[0] / l, q[1] / l, q[2] / l, q[3] / l]; }
function qrot(q, v) { const u = [q[0], q[1], q[2]], s = q[3]; const t = vscl(vcross(u, v), 2); return vadd(vadd(v, vscl(t, s)), vcross(u, t)); }
function qrand(r = rnd) { const u1 = r(), u2 = r() * TAU, u3 = r() * TAU; const a = Math.sqrt(1 - u1), b = Math.sqrt(u1); return [a * Math.sin(u2), a * Math.cos(u2), b * Math.sin(u3), b * Math.cos(u3)]; }
// rotation from orthonormal basis (columns X,Y,Z)
function qbasis(X, Y, Z) {
  const m00 = X[0], m11 = Y[1], m22 = Z[2], tr = m00 + m11 + m22; let q;
  if (tr > 0) { const s = Math.sqrt(tr + 1) * 2; q = [(Y[2] - Z[1]) / s, (Z[0] - X[2]) / s, (X[1] - Y[0]) / s, 0.25 * s]; }
  else if (m00 > m11 && m00 > m22) { const s = Math.sqrt(1 + m00 - m11 - m22) * 2; q = [0.25 * s, (Y[0] + X[1]) / s, (Z[0] + X[2]) / s, (Y[2] - Z[1]) / s]; }
  else if (m11 > m22) { const s = Math.sqrt(1 + m11 - m00 - m22) * 2; q = [(Y[0] + X[1]) / s, 0.25 * s, (Z[1] + Y[2]) / s, (Z[0] - X[2]) / s]; }
  else { const s = Math.sqrt(1 + m22 - m00 - m11) * 2; q = [(Z[0] + X[2]) / s, (Z[1] + Y[2]) / s, 0.25 * s, (X[1] - Y[0]) / s]; }
  return qnorm(q);
}
// write a 3x4 row-major instance matrix (pos, quat, uniform or xyz scale) into f at o
function instMat(f, o, p, q, s) {
  const x = q[0], y = q[1], z = q[2], w = q[3];
  const sx = typeof s === 'number' ? s : s[0], sy = typeof s === 'number' ? s : s[1], sz = typeof s === 'number' ? s : s[2];
  const xx = x * x, yy = y * y, zz = z * z, xy = x * y, xz = x * z, yz = y * z, wx = w * x, wy = w * y, wz = w * z;
  f[o] = (1 - 2 * (yy + zz)) * sx; f[o + 1] = 2 * (xy - wz) * sy; f[o + 2] = 2 * (xz + wy) * sz; f[o + 3] = p[0];
  f[o + 4] = 2 * (xy + wz) * sx; f[o + 5] = (1 - 2 * (xx + zz)) * sy; f[o + 6] = 2 * (yz - wx) * sz; f[o + 7] = p[1];
  f[o + 8] = 2 * (xz - wy) * sx; f[o + 9] = 2 * (yz + wx) * sy; f[o + 10] = (1 - 2 * (xx + yy)) * sz; f[o + 11] = p[2];
}

