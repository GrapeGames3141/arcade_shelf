// seeded RNG (mulberry32). rnd() drives the sim; frnd() is for effects only.
let RNG_S = 1;
function srand(s) { RNG_S = (s >>> 0) || 1; }
function rnd() { RNG_S = (RNG_S + 0x6D2B79F5) | 0; let t = RNG_S; t = Math.imul(t ^ (t >>> 15), t | 1); t ^= t + Math.imul(t ^ (t >>> 7), t | 61); return ((t ^ (t >>> 14)) >>> 0) / 4294967296; }
const rr = (a, b) => a + (b - a) * rnd();
