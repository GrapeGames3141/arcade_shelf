#!/usr/bin/env python3
"""Build Cartastrophe Online.

  shared/*          copy of the game parts from ../../cartastrophe/parts (refresh with: python build.py --sync)
  client/*          online-only client parts (UI + networking), injected into the game page
  src/core-server.js  authoritative match logic for the Durable Object

Outputs:
  public/cartastrophe-online.html   the browser client (served as a static asset by the Worker)
  src/sim.js                        makeSim(): the shared physics + server core wrapped in a factory, so every room
                                    gets its own copy of the game state (Durable Objects can share one isolate)
"""
import os, sys, glob, shutil

here = os.path.dirname(os.path.abspath(__file__))
P = lambda *a: os.path.join(here, *a)

if '--sync' in sys.argv:
    src = os.path.normpath(P('..', '..', 'cartastrophe', 'parts'))
    for f in glob.glob(os.path.join(src, '*')):
        shutil.copy2(f, P('shared', os.path.basename(f)))
    print('synced shared/ from', src)

read = lambda p: open(p, encoding='utf-8').read()

# ---- server sim ----
server_parts = ['10-util.js', '40-world.js', '50-physics.js']
body = ["// GENERATED by build.py from shared/ (game parts) and src/core-server.js. Do not edit.\n",
        "export function makeSim(opts) {\n'use strict';\n"]
for f in server_parts:
    body.append('// ===== shared/' + f + ' =====\n' + read(P('shared', f)).replace("'use strict';", '') + '\n')
body.append('// ===== src/core-server.js =====\n' + read(P('src', 'core-server.js')) + '\n}\n')
open(P('src', 'sim.js'), 'w', encoding='utf-8', newline='\n').write(''.join(body))

# ---- client page ----
head = read(P('shared', '00-head.html'))
ui_html = read(P('client', 'online.html'))
ui_css = read(P('client', 'online.css'))
head = head.replace('<title>Cartastrophe</title>', '<title>Cartastrophe Online (prototype)</title>')
head = head.replace('</style>', ui_css + '\n</style>')
head = head.replace('<div id="fps"></div>', ui_html + '\n<div id="fps"></div>')
js_parts = ['10-util.js', '20-gl.js', '30-meshes.js', '40-world.js', '50-physics.js', '60-ai.js', '70-game.js', '80-audio.js']
out = [head, '<script>\n']
for f in js_parts:
    out.append('// ===== shared/' + f + ' =====\n' + read(P('shared', f)) + '\n')
out.append('// ===== client/85-online.js =====\n' + read(P('client', '85-online.js')) + '\n')
out.append('// ===== shared/90-test.js =====\n' + read(P('shared', '90-test.js')) + '\n')
out.append('</script>\n</body>\n</html>\n')
os.makedirs(P('public'), exist_ok=True)
dst = P('public', 'cartastrophe-online.html')
open(dst, 'w', encoding='utf-8', newline='\n').write(''.join(out))
print('wrote', dst, os.path.getsize(dst), 'bytes;', P('src', 'sim.js'), os.path.getsize(P('src', 'sim.js')), 'bytes')
